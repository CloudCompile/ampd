"""Generate the site's derived pages from their sources of truth (#131).

The README is the source of truth for the env table and the field
notes; the OpenAPI snapshot is the source of truth for the API
reference. These pages are REGENERATED at build time — never
hand-edited (CI's route-coverage check enforces the reference half).

    python3 scripts/gen_docs.py          # writes docs/env.md,
                                         # docs/field-notes.md,
                                         # docs/api-reference.md
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")


def readme_section(heading: str) -> str:
    """The README body under `## <heading>`, up to the next same-or-higher
    heading. Fails loudly — a renamed README section must break the
    build, not silently empty the site."""
    src = open(os.path.join(ROOT, "README.md")).read()
    m = re.search(rf"^## {re.escape(heading)}\s*$(.*?)(?=^## |\Z)",
                  src, re.M | re.S)
    if not m:
        raise SystemExit(f"README: section '## {heading}' not found — "
                         "rename it in gen_docs.py too")
    return m.group(1).rstrip() + "\n"


ENV_HEADER = """<!-- GENERATED by scripts/gen_docs.py from README.md —
     do not edit; edit the README section instead. -->
# Configuration (env vars)

Every knob, its default, and what it does. Set as a plain environment
variable (or a compose env file).

"""

FIELD_HEADER = """<!-- GENERATED by scripts/gen_docs.py from README.md —
     do not edit; edit the README section instead. -->
# Field notes

Things learned by driving a real Apple Music account, encoded in the
code so you don't have to rediscover them. The README links here;
the anchors are stable (github-style slugs of each bullet's bold lead).
"""


def slug(heading: str) -> str:
    s = re.sub(r"[^\w\s-]", "", heading.lower())
    return re.sub(r"[\s_]+", "-", s).strip("-")


def field_notes_with_anchors(body: str) -> str:
    """Give each `* **Lead.** …` bullet an explicit anchor so the README
    (and everything else) can deep-link one note."""
    def _bullet(m):
        lead = m.group(1)
        return f"* <a id=\"note-{slug(lead)}\"></a>**{lead}.**{m.group(2)}"
    return re.sub(r"^\* \*\*(.+?)\.\*\*(.*)$", _bullet, body, flags=re.M)


def api_reference() -> str:
    """Markdown for every route in the OpenAPI snapshot, grouped by
    first path segment — generated, never hand-written (#130)."""
    spec = json.load(open(os.path.join(ROOT, "api", "openapi.json")))
    title = spec.get("info", {}).get("title", "tonearm")
    version = spec.get("info", {}).get("version", "?")
    out = [f"""<!-- GENERATED by scripts/gen_docs.py from api/openapi.json —
     do not edit; regenerate. The CI route-coverage check fails the build
     if any route is missing from this page. -->
# API reference

**{title}** — surface `{version}`. Every route below is from the
OpenAPI contract of record; auth (Bearer key or `?api_key=`) applies to
all `/api/` routes. Try it live at `/docs` on your own server.

"""]
    groups: dict[str, list] = {}
    for path, ops in sorted(spec.get("paths", {}).items()):
        groups.setdefault(path.split("/")[1] if path.startswith("/") else path,
                          []).append((path, ops))
    for group, entries in groups.items():
        out.append(f"## {group}\n")
        for path, ops in entries:
            for method, op in ops.items():
                if not isinstance(op, dict):
                    continue
                method_uc = method.upper()
                summary = (op.get("summary") or
                           op.get("description", "").strip().split("\n")[0]
                           or "").strip()
                anchor = path.replace("/", "").replace("{", "").replace("}", "")
                out.append(f"### `{method_uc} {path}`\n")
                if summary:
                    out.append(f"{summary}\n")
                params = op.get("parameters") or []
                if params:
                    out.append("| Parameter | In | Required | Description |")
                    out.append("|---|---|---|---|")
                    for p in params:
                        out.append(
                            f"| `{p.get('name')}` | {p.get('in')} | "
                            f"{'yes' if p.get('required') else 'no'} | "
                            f"{(p.get('description') or '').split(chr(10))[0]} |")
                    out.append("")
                body = (op.get("requestBody") or {}).get("content", {}) \
                    .get("application/json", {}).get("schema", {})
                if body:
                    out.append("Takes a JSON body (see schema in `/docs`).\n")
        out.append("")
    return "\n".join(out)


def main():
    os.makedirs(DOCS, exist_ok=True)
    env = readme_section("Configuration (env vars)")
    open(os.path.join(DOCS, "env.md"), "w").write(ENV_HEADER + env)
    notes = readme_section("Field notes (the parts the docs won't tell you)")
    open(os.path.join(DOCS, "field-notes.md"), "w").write(
        FIELD_HEADER + field_notes_with_anchors(notes))
    open(os.path.join(DOCS, "api-reference.md"), "w").write(api_reference())
    print("generated: env.md, field-notes.md, api-reference.md")


if __name__ == "__main__":
    main()
